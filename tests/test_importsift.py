import contextlib
import io
import json
import os
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import importsift
from importsift import process_file, process_text, project_root, search_roots


class Base(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = os.path.realpath(self._tmp.name)
        self.addCleanup(self._tmp.cleanup)
        importsift._SITE_CACHE.clear()

    # -- helpers ---------------------------------------------------------

    def path(self, rel):
        return os.path.join(self.root, rel.replace("/", os.sep))

    def write(self, rel, text, encoding="utf-8", newline="\n"):
        full = self.path(rel)
        parent = os.path.dirname(full)
        if parent:
            os.makedirs(parent, exist_ok=True)
        with open(full, "w", encoding=encoding, newline=newline) as handle:
            handle.write(text)
        return full

    def write_bytes(self, rel, data):
        full = self.path(rel)
        parent = os.path.dirname(full)
        if parent:
            os.makedirs(parent, exist_ok=True)
        with open(full, "wb") as handle:
            handle.write(data)
        return full

    def sort(self, text, rel="app.py", merge=False):
        full = self.write(rel, text)
        return process_file(full, merge=merge)

    def sorted_text(self, text, rel="app.py", merge=False):
        result = self.sort(text, rel=rel, merge=merge)
        self.assertIsNone(result.error, result.error)
        return result.after

    def fake_site_packages(self, *packages):
        """Add a site-packages directory holding empty packages."""
        base = self.path("env/site-packages")
        for name in packages:
            init = os.path.join(base, name.replace(".", os.sep), "__init__.py")
            os.makedirs(os.path.dirname(init), exist_ok=True)
            open(init, "w").close()
        sys.path.append(base)
        importsift._SITE_CACHE.clear()
        self.addCleanup(sys.path.remove, base)
        self.addCleanup(importsift._SITE_CACHE.clear)
        return base

    def sections(self, text, rel="app.py"):
        """Sections in the order they end up in the file."""
        result = self.sort(text, rel=rel)
        order = {name: index for index, name in enumerate(importsift.SECTION_ORDER)}
        units = sorted(result.units, key=lambda u: (order[u.section], importsift.sort_key(u)))
        return [(u.section, u.module_key) for u in units]


class TestClassification(Base):
    def test_stdlib_from_interpreter_list(self):
        self.assertEqual(self.sections("import os\n"), [("stdlib", "os")])

    def test_stdlib_modules_that_hand_maintained_lists_missed(self):
        # isort#540 was "ast is not recognised as stdlib".  sys.stdlib_module_names
        # is generated by the interpreter, so it cannot drift.
        for name in ("ast", "zoneinfo", "graphlib", "tomllib", "sqlite3", "xml"):
            with self.subTest(module=name):
                self.assertEqual(self.sections(f"import {name}\n"), [("stdlib", name)])

    def test_builtin_module_is_stdlib(self):
        self.assertEqual(self.sections("import sys\n"), [("stdlib", "sys")])

    def test_stdlib_dotted_import_uses_prefix(self):
        self.assertEqual(self.sections("import os.path\n"), [("stdlib", "os.path")])

    def test_future_always_first(self):
        self.assertEqual(
            self.sections("import os\nfrom __future__ import annotations\n"),
            [("future", "__future__"), ("stdlib", "os")],
        )

    def test_relative_import_is_local(self):
        self.assertEqual(self.sections("from . import x\n"), [("local", "")])

    def test_relative_import_with_module(self):
        self.assertEqual(self.sections("from ..pkg import x\n"), [("local", "pkg")])

    def test_local_package_is_first_party(self):
        self.write("pkg/__init__.py", "")
        self.assertEqual(self.sections("import pkg\n"), [("firstparty", "pkg")])

    def test_local_module_file_is_first_party(self):
        self.write("tools.py", "")
        self.assertEqual(self.sections("import tools\n"), [("firstparty", "tools")])

    def test_namespace_package_without_init_is_first_party(self):
        # PEP 420: a directory with no __init__.py is still importable.
        os.makedirs(self.path("nspkg/sub"))
        self.write("nspkg/sub/thing.py", "")
        self.assertEqual(self.sections("import nspkg.sub\n"), [("firstparty", "nspkg.sub")])

    def test_from_import_uses_the_submodule_not_the_namespace(self):
        # isort#1208: "from namespace import mymodule" was placed by the
        # top-level name alone, so a shared namespace landed in third-party.
        os.makedirs(self.path("shared/inhouse"))
        self.write("shared/inhouse/__init__.py", "")
        self.assertEqual(
            self.sections("from shared import inhouse\n"),
            [("firstparty", "shared")],
        )

    def test_src_layout_is_first_party(self):
        self.write("pyproject.toml", "")
        self.write("src/app/models.py", "")
        self.assertEqual(
            self.sections("from app.models import Order\n"), [("firstparty", "app.models")]
        )

    def test_monorepo_nested_package_is_first_party(self):
        # isort#1704: two libraries sharing a prefix inside one repository.
        self.write("pyproject.toml", "")
        self.write("libs/first_lib/my/first/library/__init__.py", "")
        self.assertEqual(
            self.sections("from my.first.library import thing\n", rel="libs/first_lib/mod.py"),
            [("firstparty", "my.first.library")],
        )

    def test_installed_package_is_third_party(self):
        self.fake_site_packages("requests")
        self.assertEqual(self.sections("import requests\n"), [("thirdparty", "requests")])

    def test_unknown_name_falls_back_to_third_party(self):
        result = self.sort("import definitely_not_installed_xyz\n")
        self.assertEqual(result.units[0].section, "thirdparty")
        self.assertIn("unresolved", result.units[0].evidence)

    def test_evidence_names_the_file_it_found(self):
        self.write("pkg/__init__.py", "")
        result = self.sort("import pkg\n")
        self.assertIn("pkg/__init__.py", result.units[0].evidence)

    def test_local_shadow_of_stdlib_is_reported(self):
        self.write("json.py", "")
        result = self.sort("import json\n")
        self.assertEqual(result.units[0].section, "stdlib")
        self.assertTrue(any("shadows" in w for w in result.warnings), result.warnings)

    def test_third_party_is_stable_whether_installed_or_not(self):
        # The section must not depend on whether the package happens to be
        # installed on this machine -- that is the CI/laptop split.
        before = self.sort("import requests\n").units[0].section
        self.fake_site_packages("requests")
        after = self.sort("import requests\n").units[0].section
        self.assertEqual(before, after)


class TestOrdering(Base):
    def test_sections_in_order(self):
        text = "from . import here\nimport requests\nimport os\nfrom __future__ import annotations\n"
        self.fake_site_packages("requests")
        out = self.sorted_text(text)
        self.assertEqual(
            out,
            "from __future__ import annotations\n\nimport os\n\nimport requests\n\nfrom . import here\n",
        )

    def test_straight_imports_before_from_imports(self):
        out = self.sorted_text("from os import path\nimport os\n")
        self.assertEqual(out, "import os\nfrom os import path\n")

    def test_sorting_is_case_insensitive(self):
        self.fake_site_packages("Zebra", "apple")
        out = self.sorted_text("import Zebra\nimport apple\n")
        self.assertEqual(out, "import apple\nimport Zebra\n")

    def test_one_blank_line_between_sections_only(self):
        self.fake_site_packages("requests")
        self.write("pkg/__init__.py", "")
        out = self.sorted_text("import os\n\n\n\nimport requests\n\n\nimport pkg\n")
        self.assertEqual(out, "import os\n\nimport requests\n\nimport pkg\n")

    def test_multi_name_import_is_split_per_name(self):
        # One line can only sit in one section, and the names may belong to
        # different ones, so each name gets its own line.
        self.fake_site_packages("requests")
        out = self.sorted_text("import requests, os\n")
        self.assertEqual(out, "import os\n\nimport requests\n")

    def test_multi_name_import_of_one_section_is_still_split(self):
        out = self.sorted_text("import sys, os\n")
        self.assertEqual(out, "import os\nimport sys\n")

    def test_split_keeps_aliases(self):
        out = self.sorted_text("import sys, os.path as p\n")
        self.assertEqual(out, "import os.path as p\nimport sys\n")

    def test_trailing_code_is_not_touched(self):
        out = self.sorted_text("import os\n\n\nX = 1\n\n\ndef f():\n    pass\n")
        self.assertEqual(out, "import os\n\n\nX = 1\n\n\ndef f():\n    pass\n")


class TestComments(Base):
    def test_trailing_comment_travels(self):
        out = self.sorted_text("import sys  # keep me\nimport os\n")
        self.assertEqual(out, "import os\nimport sys  # keep me\n")

    def test_leading_comment_travels(self):
        out = self.sorted_text("import sys\n# about os\nimport os\n")
        self.assertEqual(out, "# about os\nimport os\nimport sys\n")

    def test_shebang_and_coding_cookie_never_move(self):
        text = "#!/usr/bin/env python\n# -*- coding: utf-8 -*-\nimport sys\nimport os\n"
        out = self.sorted_text(text)
        self.assertEqual(
            out, "#!/usr/bin/env python\n# -*- coding: utf-8 -*-\nimport os\nimport sys\n"
        )

    def test_commented_out_names_survive_a_sort(self):
        # The exact shape from isort#1852, where the commented-out names are
        # folded into a single inline comment and the file is mangled.
        text = (
            "import requests\n"
            "from dj_rest_auth.views import (\n"
            "    LoginView,\n"
            "    LogoutView,\n"
            "    # PasswordChangeView,\n"
            "    # PasswordResetConfirmView,\n"
            ")\n"
            "import os\n"
        )
        out = self.sorted_text(text)
        for name in ("# PasswordChangeView,", "# PasswordResetConfirmView,"):
            self.assertIn(name, out)
        self.assertNotIn(";", out)
        self.assertEqual(out.count("LoginView"), 1)
        self.assertEqual(
            out,
            "import os\n\n"
            "import requests\n"
            "from dj_rest_auth.views import (\n"
            "    LoginView,\n"
            "    LogoutView,\n"
            "    # PasswordChangeView,\n"
            "    # PasswordResetConfirmView,\n"
            ")\n",
        )

    def test_skip_marker_pins_a_statement(self):
        text = "import sys\nimport os  # isort: skip\nimport abc\n"
        self.assertEqual(self.sorted_text(text), text)

    def test_off_and_on_are_respected(self):
        text = (
            "import sys\n"
            "import os\n"
            "# isort: off\n"
            "import zlib\n"
            "import abc\n"
            "# isort: on\n"
        )
        out = self.sorted_text(text)
        self.assertEqual(
            out,
            "import os\nimport sys\n# isort: off\nimport zlib\nimport abc\n# isort: on\n",
        )

    def test_frozen_region_is_a_boundary(self):
        # Sorting must not jump over a region the user pinned.
        text = "import sys\n# isort: off\nimport zlib\n# isort: on\nimport abc\n"
        self.assertEqual(self.sorted_text(text), text)

    def test_skip_file_leaves_everything_alone(self):
        text = "# isort: skip_file\nimport sys\nimport os\n"
        result = self.sort(text)
        self.assertTrue(result.skipped)
        self.assertFalse(result.changed)

    def test_floating_comment_splits_the_block(self):
        # A comment on its own line, separated from both sides, marks a
        # boundary the tool will not sort across.
        text = "import sys\n\n# ---- helpers ----\n\nimport os\n"
        self.assertEqual(self.sorted_text(text), text)


class TestSafety(Base):
    def test_import_set_is_unchanged(self):
        import ast

        text = (
            "import sys, os\n"
            "from typing import (Any, Dict)\n"
            "import requests as req\n"
            "from . import x as y\n"
            "from ..pkg import thing\n"
        )
        out = self.sorted_text(text)
        self.assertEqual(
            importsift.import_signature(ast.parse(text)),
            importsift.import_signature(ast.parse(out)),
        )

    def test_aliased_and_plain_import_of_one_module(self):
        # Both signatures start with the same four fields, so the alias is
        # the only thing left to compare -- and it may be None.
        text = "import os as o\nimport os\n"
        out = self.sorted_text(text)
        self.assertEqual(out, "import os\nimport os as o\n")

    def test_sorting_twice_changes_nothing(self):
        text = "import requests\nimport os\nfrom typing import Any\nfrom . import x\n"
        once = self.sorted_text(text)
        twice = self.sorted_text(once)
        self.assertEqual(once, twice)

    def test_syntax_error_is_reported_not_written(self):
        result = self.sort("def broken(:\n    pass\n")
        self.assertIsNotNone(result.error)
        self.assertIn("cannot parse", result.error)
        self.assertFalse(result.changed)

    def test_statement_sharing_a_line_is_left_alone(self):
        text = "import requests; import os\nimport sys\n"
        self.assertEqual(self.sorted_text(text), text)

    def test_try_except_imports_are_left_alone(self):
        text = (
            "import os\n"
            "try:\n"
            "    import ujson as json\n"
            "except ImportError:\n"
            "    import json\n"
        )
        self.assertEqual(self.sorted_text(text), text)

    def test_type_checking_block_is_left_alone(self):
        text = (
            "from typing import TYPE_CHECKING\n"
            "import os\n"
            "\n"
            "if TYPE_CHECKING:\n"
            "    import requests\n"
        )
        out = self.sorted_text(text)
        self.assertIn("if TYPE_CHECKING:\n    import requests\n", out)

    def test_crlf_is_preserved(self):
        full = self.write("crlf.py", "import sys\r\nimport os\r\n", newline="")
        result = process_file(full)
        self.assertTrue(result.changed)
        with open(full, "wb") as handle:
            handle.write(result.after_bytes)
        with open(full, "rb") as handle:
            data = handle.read()
        self.assertEqual(data, b"import os\r\nimport sys\r\n")

    def test_bom_is_preserved(self):
        full = self.write_bytes("bom.py", b"\xef\xbb\xbfimport sys\nimport os\n")
        result = process_file(full)
        with open(full, "wb") as handle:
            handle.write(result.after_bytes)
        with open(full, "rb") as handle:
            data = handle.read()
        self.assertTrue(data.startswith(b"\xef\xbb\xbf"))
        self.assertEqual(data, b"\xef\xbb\xbfimport os\nimport sys\n")

    def test_missing_final_newline_is_preserved(self):
        full = self.write("noeol.py", "import sys\nimport os", newline="")
        result = process_file(full)
        with open(full, "wb") as handle:
            handle.write(result.after_bytes)
        with open(full, "rb") as handle:
            self.assertEqual(handle.read(), b"import os\nimport sys")

    def test_latin1_coding_cookie_is_preserved(self):
        text = "# -*- coding: latin-1 -*-\nimport sys\nimport os\n# caf\xe9\n"
        full = self.write("cookie.py", text, encoding="latin-1", newline="")
        result = process_file(full)
        with open(full, "wb") as handle:
            handle.write(result.after_bytes)
        with open(full, "rb") as handle:
            data = handle.read()
        self.assertEqual(data.decode("latin-1"), "# -*- coding: latin-1 -*-\nimport os\nimport sys\n# caf\xe9\n")

    def test_the_working_directory_is_never_read(self):
        # The whole "same file, same answer" claim rests on this: the tool
        # must not consult the process working directory at all.
        text = "import sys\nimport os\n"
        full = self.write("pkg/app.py", text)
        original = os.getcwd

        def boom():
            raise AssertionError("importsift read the working directory")

        os.getcwd = boom
        try:
            result = process_file(full)
        finally:
            os.getcwd = original
        self.assertEqual(result.after, "import os\nimport sys\n")

    def test_empty_file_is_skipped(self):
        result = self.sort("")
        self.assertFalse(result.changed)
        self.assertIsNone(result.error)

    def test_file_without_imports_is_skipped(self):
        result = self.sort("X = 1\n")
        self.assertTrue(result.skipped)
        self.assertFalse(result.changed)

    def test_identical_output_from_any_working_directory(self):
        self.write("pyproject.toml", "")
        self.write("src/app/__init__.py", "")
        text = "import requests\nimport os\nfrom app import models\n"
        full = self.write("src/app/mod.py", text)
        here = os.getcwd()
        try:
            os.chdir(self.root)
            first = process_file(full).after
            os.chdir(os.path.join(self.root, "src", "app"))
            second = process_file(full).after
        finally:
            os.chdir(here)
        self.assertEqual(first, second)


class TestMerge(Base):
    def test_merge_same_module(self):
        out = self.sorted_text("from os import path\nfrom os import sep\n", merge=True)
        self.assertEqual(out, "from os import path, sep\n")

    def test_merge_keeps_aliases(self):
        out = self.sorted_text("from os import path as p\nfrom os import sep\n", merge=True)
        self.assertEqual(out, "from os import path as p, sep\n")

    def test_no_merge_across_different_modules(self):
        out = self.sorted_text("from os import path\nfrom sys import argv\n", merge=True)
        self.assertEqual(out, "from os import path\nfrom sys import argv\n")

    def test_no_merge_when_a_comment_would_be_lost(self):
        text = "from os import path  # why\nfrom os import sep\n"
        self.assertEqual(self.sorted_text(text, merge=True), text)

    def test_no_merge_when_a_leading_comment_is_present(self):
        text = "# keep\nfrom os import path\nfrom os import sep\n"
        self.assertEqual(self.sorted_text(text, merge=True), text)


class TestProjectRoots(Base):
    def test_project_root_found_by_marker(self):
        self.write("pyproject.toml", "")
        self.write("a/b/c.py", "")
        self.assertEqual(project_root(self.path("a/b/c.py")), self.root)

    def test_project_root_falls_back_to_the_file_directory(self):
        self.write("a/b/c.py", "")
        self.assertEqual(project_root(self.path("a/b/c.py")), self.path("a/b"))

    def test_search_roots_include_src_and_every_ancestor(self):
        self.write("pyproject.toml", "")
        self.write("src/pkg/mod.py", "")
        roots = search_roots(self.path("src/pkg/mod.py"), self.root)
        self.assertIn(os.path.join(self.root, "src"), roots)
        self.assertIn(self.root, roots)
        self.assertIn(self.path("src/pkg"), roots)


class TestCommandLine(Base):
    def run_cli(self, *argv):
        buffer = io.StringIO()
        with contextlib.redirect_stdout(buffer), contextlib.redirect_stderr(io.StringIO()):
            code = importsift.main(list(argv))
        return code, buffer.getvalue()

    def test_check_reports_and_exits_one(self):
        full = self.write("app.py", "import sys\nimport os\n")
        code, out = self.run_cli("--check", full)
        self.assertEqual(code, 1)
        self.assertIn("would sort", out)
        with open(full, encoding="utf-8") as handle:
            self.assertEqual(handle.read(), "import sys\nimport os\n")

    def test_check_is_silent_when_clean(self):
        full = self.write("app.py", "import os\n")
        code, out = self.run_cli("--check", full)
        self.assertEqual(code, 0)
        self.assertEqual(out.strip(), "")

    def test_diff_never_writes(self):
        full = self.write("app.py", "import sys\nimport os\n")
        code, out = self.run_cli("--diff", full)
        self.assertEqual(code, 0)
        self.assertIn("+import os", out)
        self.assertIn("-import os", out)
        with open(full, encoding="utf-8") as handle:
            self.assertEqual(handle.read(), "import sys\nimport os\n")

    def test_explain_prints_evidence(self):
        self.write("pkg/__init__.py", "")
        full = self.write("app.py", "import os\nimport pkg\n")
        code, out = self.run_cli("--explain", full)
        self.assertEqual(code, 0)
        self.assertIn("stdlib", out)
        self.assertIn("sys.stdlib_module_names", out)
        self.assertIn("firstparty", out)

    def test_json_is_machine_readable(self):
        full = self.write("app.py", "import os\nimport sys\n")
        code, out = self.run_cli("--json", full)
        self.assertEqual(code, 0)
        payload = json.loads(out)
        self.assertEqual(payload[0]["path"], full)
        self.assertEqual(
            [item["module"] for item in payload[0]["imports"]], ["os", "sys"]
        )

    def test_default_run_writes_the_file(self):
        full = self.write("app.py", "import sys\nimport os\n")
        code, out = self.run_cli(full)
        self.assertEqual(code, 0)
        self.assertIn("sorted", out)
        with open(full, encoding="utf-8") as handle:
            self.assertEqual(handle.read(), "import os\nimport sys\n")

    def test_directory_walk_skips_virtualenvs_and_caches(self):
        self.write("a.py", "import sys\nimport os\n")
        self.write(".venv/lib/x.py", "import sys\nimport os\n")
        self.write("__pycache__/y.py", "import sys\nimport os\n")
        code, out = self.run_cli("--check", self.root)
        self.assertIn("a.py", out)
        self.assertNotIn(".venv", out)
        self.assertNotIn("__pycache__", out)

    def test_parse_error_exits_two(self):
        full = self.write("bad.py", "def f(:\n")
        code, _ = self.run_cli("--check", full)
        self.assertEqual(code, 2)

    def test_missing_path_exits_two(self):
        code, _ = self.run_cli("--check", self.path("nope.py"))
        self.assertEqual(code, 2)

    def test_quiet_prints_nothing(self):
        full = self.write("app.py", "import sys\nimport os\n")
        code, out = self.run_cli("--quiet", full)
        self.assertEqual(code, 0)
        self.assertEqual(out, "")


class TestEdgeCases(Base):
    def test_only_imports_no_newline_at_end(self):
        full = self.write("x.py", "import sys\nimport os", newline="")
        result = process_file(full)
        self.assertEqual(result.after, "import os\nimport sys")

    def test_multiline_from_import_with_trailing_comment(self):
        text = "import os\nfrom a import (\n    x,\n)  # note\n"
        out = self.sorted_text(text)
        self.assertIn(")  # note", out)

    def test_docstring_before_imports_stays_first(self):
        text = '"""Doc."""\nimport sys\nimport os\n'
        out = self.sorted_text(text)
        self.assertEqual(out, '"""Doc."""\nimport os\nimport sys\n')

    def test_blank_lines_before_first_import_are_kept(self):
        text = '"""Doc."""\n\n\nimport sys\nimport os\n'
        out = self.sorted_text(text)
        self.assertTrue(out.startswith('"""Doc."""\n\n\nimport os\n'))

    def test_form_feed_inside_source_does_not_split_a_line(self):
        text = "import sys\nimport os\nX = 1\x0c\n"
        out = self.sorted_text(text)
        self.assertIn("X = 1\x0c", out)

    def test_tabs_are_preserved(self):
        text = "import sys\n\t\nimport os\n"
        out = self.sorted_text(text)
        self.assertEqual(out, "import os\nimport sys\n")


