def sort_key(unit: Unit) -> tuple:
    """Total order that depends on the statement's text, not on input order.

    The alias is part of the key so that ``import os`` and ``import os as o``
    always come out the same way round, no matter which one came first.
    """
    return (
        0 if unit.kind == 0 else 1,
        unit.module_key.lower(),
        unit.module_key,
        unit.level,
        unit.tail,
    )


def merge_units(units: list[Unit]) -> list[Unit]:
    """Merge adjacent ``from x import a`` / ``from x import b`` pairs.

    Only when nothing can be lost: one line each, no leading comment, no
    trailing comment, same module and level.  Anything else is left alone,
    because merging a commented statement is how the other tools end up
    rewriting your comments into a single line.
    """
    merged: list[Unit] = []
    for unit in units:
        previous = merged[-1] if merged else None
        if (
            previous is not None
            and previous.kind == 1
            and unit.kind == 1
            and previous.level == unit.level
            and previous.module_key == unit.module_key
            and previous.first == previous.last
            and unit.first == unit.last
            and previous.node is not None
            and unit.node is not None
            and previous.first == previous.node.lineno - 1
            and unit.first == unit.node.lineno - 1
            and "#" not in previous.lines[-1]
            and "#" not in unit.lines[-1]
        ):
            names = [
                alias.name + (f" as {alias.asname}" if alias.asname else "")
                for node in (previous.node, unit.node)
                for alias in node.names
            ]
            dots = "." * previous.level
            joined = ", ".join(names)
            previous.lines = [f"from {dots}{previous.module_key} import {joined}"]
            previous.names = previous.names + unit.names
            previous.tail = joined
            previous.node = None
            continue
        merged.append(unit)
    return merged


def render_block(block: list[Unit], merge: bool) -> list[str]:
    if len(block) == 1 and block[0].frozen:
        return list(block[0].lines)

    units = merge_units(block) if merge else list(block)

    groups: dict[str, list[Unit]] = {}
    for unit in units:
        groups.setdefault(unit.section, []).append(unit)

    out: list[str] = []
    for section in SECTION_ORDER:
        members = groups.get(section)
        if not members:
            continue
        members.sort(key=sort_key)
        if out:
            out.append("")
        for unit in members:
            out.extend(unit.lines)
    return out


