#!/usr/bin/env python3
"""importsift - put every import in its place, and say why it went there.

An import belongs to one of five sections: ``__future__``, the standard
library, third-party packages, your own package, or a relative import.
Which section that is, is not a matter of taste -- it is a fact about the
interpreter you run and the files on disk.  importsift works that fact out
from evidence, prints the evidence, and moves the lines that make up the
import block without rewriting them.

Two rules keep the rewrite safe:

1. **Only whole lines move.**  A statement, its trailing comment and the
   comment lines directly above it travel as one opaque block of text.  The
   tool never re-serialises an import, so it cannot eat a comment.
2. **Every write is verified.**  Before a file is written it is parsed
   again and the set of imported names is compared with the original.  If a
   single name appeared or disappeared, nothing is written.

Standard library only.  No configuration file.  Python 3.10+.
"""

from __future__ import annotations

import argparse
import ast
import difflib
import glob
import io
import json
import os
import re
import sys
import sysconfig
import tokenize
from collections import Counter
