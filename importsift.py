def project_root(path: str) -> str:
    """Walk up from *path* to the first directory that looks like a project.

    The result never depends on the working directory: it is a function of
    the file's own location.  That is the whole point -- the same file sorts
    the same way whether you run from the repository root or from a nested
    directory.
    """
    here = os.path.dirname(os.path.abspath(path))
    start = here
    while True:
        for marker in PROJECT_MARKERS:
            if os.path.exists(os.path.join(here, marker)):
                return here
        parent = os.path.dirname(here)
        if parent == here:
            return start
        here = parent


def search_roots(path: str, root: str) -> list[str]:
    """Directories where a dotted name may begin.

    Ordered most specific first: ``src`` and ``lib`` layouts, then the
    project root, then every directory between the file and the root.  The
    last part is what makes a monorepo work: a file at
    ``libs/api/api/v1/views.py`` can see ``api.v1`` because ``libs/api`` is
    on the list, without being told so in a config file.
    """
    here = os.path.dirname(os.path.abspath(path))
    candidates: list[str] = [
        os.path.join(root, "src"),
        os.path.join(root, "lib"),
        root,
    ]

    walk = here
    chain = [here]
    while os.path.normcase(walk) != os.path.normcase(root):
        parent = os.path.dirname(walk)
        if parent == walk:
            break
        chain.append(parent)
        walk = parent
    candidates.extend(chain)

    out: list[str] = []
    seen: set[str] = set()
    for c in candidates:
        key = os.path.normcase(os.path.abspath(c))
        if key in seen or not os.path.isdir(c):
            continue
        seen.add(key)
        out.append(os.path.abspath(c))
    return out


_SITE_CACHE: dict[str, list[str]] = {}


def site_dirs(root: str) -> list[str]:
    """Directories that hold installed packages, for the project and for us.

    Only ``site-packages`` style directories are searched.  A name that is
    importable from somewhere else (``PYTHONPATH``, a checkout) will be
    reported as unresolved, which is honest: it is not installed.
    """
    key = os.path.normcase(root)
    if key in _SITE_CACHE:
        return _SITE_CACHE[key]

    paths = sysconfig.get_paths()
    stdlib_dirs = {
        os.path.normcase(os.path.abspath(p))
        for p in (paths.get("stdlib"), paths.get("platstdlib"))
        if p
    }

    out: list[str] = []
    for entry in sys.path:
        if not entry:
            continue
        norm = os.path.normcase(os.path.abspath(entry))
        if norm in stdlib_dirs:
            continue
        base = os.path.basename(norm)
        if base in ("site-packages", "dist-packages"):
            out.append(entry)

    for pattern in (
        ".venv/Lib/site-packages",
        "venv/Lib/site-packages",
        ".venv/lib/*/site-packages",
        "venv/lib/*/site-packages",
    ):
        out.extend(glob.glob(os.path.join(root, pattern)))

    deduped: list[str] = []
    seen: set[str] = set()
    for d in out:
        norm = os.path.normcase(os.path.abspath(d))
        if norm in seen or not os.path.isdir(d):
            continue
        seen.add(norm)
        deduped.append(d)
    _SITE_CACHE[key] = deduped
    return deduped


def find_in(dirs: list[str], dotted: str) -> str | None:
    """Return the path a dotted name occupies inside one of *dirs*."""
    rel = dotted.replace(".", os.sep)
    for base_dir in dirs:
        base = os.path.join(base_dir, rel)
        if os.path.isfile(base + ".py"):
            return base + ".py"
        init = os.path.join(base, "__init__.py")
        if os.path.isfile(init):
            return init
        if os.path.isdir(base):
            # A directory with no __init__.py is still importable: PEP 420
            # namespace packages are how monorepos share a prefix.
            return base
    return None


def shorten(path: str, root: str) -> str:
    """Path relative to the project, with forward slashes."""
    try:
        rel = os.path.relpath(path, root)
    except ValueError:
        return path.replace("\\", "/")
    if rel.startswith(".."):
        return path.replace("\\", "/")
    return rel.replace("\\", "/")


