def module_level_imports(tree: ast.Module) -> list[ast.AST]:
    return [
        node
        for node in tree.body
        if isinstance(node, (ast.Import, ast.ImportFrom))
    ]


#: A shebang or a coding cookie has to stay on its line: moving either one
#: breaks the file, so they are never absorbed into an import's block.
PINNED_RE = re.compile(r"^#!|^#.*coding[:=]\s*[-\w.]+")


def _pinned(line: str) -> bool:
    return bool(PINNED_RE.match(line))


def _leading_start(lines: list[str], statement_row: int, floor: int) -> int:
    """Extend a statement upwards over the comment lines glued to it.

    A comment directly above an import almost always describes that import,
    so it travels with it.  The exceptions are the two lines Python itself
    reads before anything else.
    """
    start = statement_row
    while start - 1 >= floor and is_comment(lines[start - 1]) and not _pinned(lines[start - 1]):
        start -= 1
    return start


def _trailing_comment(lines: list[str], last_row: int) -> str:
    """The ``# ...`` at the end of a statement, if any.

    Import statements cannot contain string literals, so the first ``#`` on
    the line is a comment.
    """
    line = lines[last_row]
    index = line.find("#")
    return line[index:] if index >= 0 else ""


def build_unit(
    node: ast.AST,
    lines: list[str],
    floor: int,
    roots: list[str],
    root: str,
    comments: dict[int, list[str]],
) -> Unit:
    first_row = node.lineno - 1
    last_row = (node.end_lineno or node.lineno) - 1
    start = _leading_start(lines, first_row, floor)

    if isinstance(node, ast.Import):
        section, evidence = classify_import(node, roots, root)
        module_key = node.names[0].name
        kind = 0
        level = 0
        names = tuple(alias.name for alias in node.names)
    else:
        section, evidence = classify_from(node, roots, root)
        module_key = node.module or ""
        kind = 1
        level = node.level
        names = tuple(alias.name for alias in node.names)

    return Unit(
        node=node,
        first=start,
        last=last_row,
        lines=list(lines[start : last_row + 1]),
        section=section,
        evidence=evidence,
        module_key=module_key,
        kind=kind,
        level=level,
        frozen=has_skip_marker(comments, node.lineno, last_row + 1),
        names=names,
        tail=", ".join(
            alias.name + (f" as {alias.asname}" if alias.asname else "")
            for alias in node.names
        ),
    )


def expand_multi_import(unit: Unit, roots: list[str], root: str) -> list[Unit]:
    """Split ``import a, b`` into one line per name.

    A line holding two names can only ever be placed in one section, and the
    two names are free to sort to different places.  Splitting costs a line
    and buys the ability to place each name on its own evidence; the names
    and aliases are copied across unchanged, so nothing is imported that was
    not imported before.
    """
    node = unit.node
    if not isinstance(node, ast.Import) or len(node.names) < 2 or unit.frozen:
        return [unit]
    if unit.first != unit.last:
        return [unit]

    placed = []
    for alias in node.names:
        found = resolve(alias.name, roots, root)
        placed.append(found or ("thirdparty", "unresolved: not on any path"))

    line = unit.lines[-1]
    comment = _trailing_comment(unit.lines, len(unit.lines) - 1)
    prefix = line[: line.find("#")] if comment else line
    indent = prefix[: len(prefix) - len(prefix.lstrip())]

    pieces: list[Unit] = []
    for alias, (section, evidence) in zip(node.names, placed):
        text = f"{indent}import {alias.name}"
        if alias.asname:
            text += f" as {alias.asname}"
        piece = Unit(
            node=None,
            first=unit.first,
            last=unit.last,
            lines=[text],
            section=section,
            evidence=evidence,
            module_key=alias.name,
            kind=0,
            synthetic=True,
            names=(alias.name,),
            tail=alias.name + (f" as {alias.asname}" if alias.asname else ""),
        )
        pieces.append(piece)

    pieces[0].lines = unit.lines[:-1] + pieces[0].lines
    if comment:
        pieces[-1].lines[-1] = pieces[-1].lines[-1] + "  " + comment.lstrip()
    return pieces


def build_blocks(units: list[Unit], lines: list[str]) -> list[list[Unit]]:
    """Group adjacent units into blocks that may be sorted independently.

    A block ends wherever something appears that is not an import, a blank
    line or a comment attached to the next import -- a statement, a
    ``try:`` block, a ``# isort: skip`` line, or a comment floating on its
    own.  Sorting across such a boundary would reorder code the user put
    there on purpose.
    """
    blocks: list[list[Unit]] = []
    current: list[Unit] = []

    for unit in units:
        if unit.frozen:
            if current:
                blocks.append(current)
                current = []
            blocks.append([unit])
            continue
        if current:
            gap = lines[current[-1].last + 1 : unit.first]
            if all(is_blank(line) for line in gap):
                current.append(unit)
                continue
            blocks.append(current)
        current = [unit]

    if current:
        blocks.append(current)
    return blocks


