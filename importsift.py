# --------------------------------------------------------------------------
# constants
# --------------------------------------------------------------------------

SECTION_ORDER = ("future", "stdlib", "thirdparty", "firstparty", "local")

SECTION_LABEL = {
    "future": "future",
    "stdlib": "stdlib",
    "thirdparty": "third-party",
    "firstparty": "first-party",
    "local": "local",
}

#: Files and directories that mark the top of a project.  The search stops
#: at the first one found while walking up from the file being sorted.
PROJECT_MARKERS = (
    ".git",
    "pyproject.toml",
    "setup.py",
    "setup.cfg",
    "tox.ini",
    "Pipfile",
    "poetry.lock",
)

#: Never descended into when a directory is given on the command line.
SKIP_DIRS = frozenset(
    {
        ".git",
        ".hg",
        ".svn",
        ".tox",
        ".nox",
        ".mypy_cache",
        ".pytest_cache",
        ".ruff_cache",
        "__pycache__",
        "node_modules",
        "site-packages",
        "dist-packages",
        "build",
        "dist",
        ".eggs",
    }
)

#: ``# isort: skip`` and friends are read because they are already written
#: into thousands of files; dropping them would silently undo a user's
#: deliberate choice.
MARKER_RE = re.compile(r"#\s*isort:\s*(skip_file|skip|off|on|split)\b", re.IGNORECASE)

#: The standard library of *this* interpreter, plus the modules compiled in.
#: ``sys.stdlib_module_names`` exists from 3.10 and is generated by CPython
#: itself, so it cannot drift the way a hand-maintained list does.
STDLIB = frozenset(sys.stdlib_module_names) | frozenset(sys.builtin_module_names)


# --------------------------------------------------------------------------
# data
# --------------------------------------------------------------------------


@dataclass
class Unit:
    """One thing that gets moved: a statement plus its comments."""

    node: ast.AST | None
    first: int  # 0-based index of the first line of the unit
    last: int  # 0-based index of the last line, inclusive
    lines: list[str]
    section: str
    evidence: str
    module_key: str
    kind: int  # 0 = ``import x``, 1 = ``from x import y``
    level: int = 0
    frozen: bool = False
    synthetic: bool = False
    names: tuple[str, ...] = ()
    tail: str = ""


@dataclass
class FileResult:
    path: str
    changed: bool = False
    before: str = ""
    after: str = ""
    units: list[Unit] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    error: str | None = None
    skipped: bool = False
    encoding: str = "utf-8"
    newline: str = "\n"
    ends_with_newline: bool = True
    after_bytes: bytes = b""


