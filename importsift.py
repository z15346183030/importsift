def unified_diff(result: FileResult, newline: str) -> str:
    before = result.before.splitlines()
    after = result.after.splitlines()
    return "".join(
        difflib.unified_diff(
            [line + newline for line in before],
            [line + newline for line in after],
            fromfile=f"{result.path}:before",
            tofile=f"{result.path}:after",
            n=3,
        )
    )


def explain(result: FileResult) -> str:
    out = [f"{result.path}"]
    width = max((len(unit.section) for unit in result.units), default=8)
    name_width = max((len(unit.module_key or ".") for unit in result.units), default=1)
    for unit in result.units:
        if unit.frozen:
            label = "pinned"
            evidence = "skip marker"
        else:
            label = unit.section
            evidence = unit.evidence
        name = unit.module_key or "." * max(unit.level, 1)
        out.append(
            f"  line {unit.first + 1:>4}  {label:<{width}}  "
            f"{name:<{name_width}}  {evidence}"
        )
    for warning in result.warnings:
        out.append(f"  warning: {warning}")
    return "\n".join(out)


def result_json(result: FileResult) -> dict:
    return {
        "path": result.path,
        "changed": result.changed,
        "skipped": result.skipped,
        "error": result.error,
        "warnings": result.warnings,
        "imports": [
            {
                "line": unit.first + 1,
                "section": "pinned" if unit.frozen else unit.section,
                "module": unit.module_key,
                "level": unit.level,
                "names": list(unit.names),
                "evidence": unit.evidence,
            }
            for unit in result.units
        ],
    }


