# the safety net
# --------------------------------------------------------------------------


def import_signature(tree: ast.Module) -> list[tuple]:
    """Every import in the file, as a sorted bag of tuples.

    Order is dropped on purpose -- that is what we are changing.  What must
    not change is the set of names: module, level, name and alias.
    """
    signature: list[tuple] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                signature.append(("import", 0, "", alias.name, alias.asname or ""))
        elif isinstance(node, ast.ImportFrom):
            for alias in node.names:
                signature.append(
                    ("from", node.level, node.module or "", alias.name, alias.asname or "")
                )
    return sorted(signature)


def safe_to_write(before_tree: ast.Module, after_text: str) -> tuple[bool, str]:
    try:
        after_tree = ast.parse(after_text)
    except SyntaxError as exc:
        return (False, f"rewrite would not parse: {exc.msg} (line {exc.lineno})")

    before = import_signature(before_tree)
    after = import_signature(after_tree)
    if before == after:
        return (True, "")

    before_count = Counter(before)
    after_count = Counter(after)
    lost = sorted((before_count - after_count).elements())
    gained = sorted((after_count - before_count).elements())
    parts = []
    if lost:
        parts.append(f"lost {lost[:3]}")
    if gained:
        parts.append(f"gained {gained[:3]}")
    return (False, "rewrite changes what is imported: " + "; ".join(parts))


