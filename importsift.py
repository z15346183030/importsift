_RESOLVE_CACHE: dict[tuple, tuple[str, str] | None] = {}


def resolve(dotted: str, roots: list[str], root: str) -> tuple[str, str] | None:
    """Place a dotted name by evidence, trying the longest prefix first.

    Longest prefix first is what fixes ``from backports import zoneinfo``:
    the top-level ``backports`` may be shared by several distributions, but
    ``backports.zoneinfo`` is one specific thing and can be looked up.

    Results are memoised: a repository imports ``os`` a few thousand times,
    and each miss costs a handful of ``stat`` calls.
    """
    key = (root, tuple(roots), dotted)
    if key in _RESOLVE_CACHE:
        return _RESOLVE_CACHE[key]
    if len(_RESOLVE_CACHE) > 50_000:
        _RESOLVE_CACHE.clear()

    parts = dotted.split(".")
    answer: tuple[str, str] | None = None
    for size in range(len(parts), 0, -1):
        candidate = ".".join(parts[:size])
        note = "" if candidate == dotted else f" (matched prefix {candidate})"
        if candidate in STDLIB:
            answer = ("stdlib", f"{candidate} in sys.stdlib_module_names{note}")
            break
        local = find_in(roots, candidate)
        if local:
            answer = ("firstparty", shorten(local, root) + note)
            break
        installed = find_in(site_dirs(root), candidate)
        if installed:
            answer = ("thirdparty", shorten(installed, root) + note)
            break

    _RESOLVE_CACHE[key] = answer
    return answer


def classify_import(node: ast.Import, roots: list[str], root: str) -> tuple[str, str]:
    name = node.names[0].name
    if name == "__future__":
        return ("future", "__future__ always sorts first")
    found = resolve(name, roots, root)
    if found:
        return found
    return ("thirdparty", "unresolved: not on any path")


def classify_from(
    node: ast.ImportFrom, roots: list[str], root: str
) -> tuple[str, str]:
    if node.level:
        return ("local", f"relative import, level {node.level}")
    module = node.module or ""
    if module == "__future__":
        return ("future", "__future__ always sorts first")

    base = resolve(module, roots, root) if module else None
    if base and base[0] in ("firstparty", "stdlib"):
        return base

    # ``from namespace import mymodule`` names one specific submodule.  If
    # that submodule lives in this tree, the statement is first-party even
    # when the namespace itself is shared with other projects.
    for alias in node.names:
        deeper = resolve(f"{module}.{alias.name}", roots, root) if module else None
        if deeper and deeper[0] == "firstparty":
            return (deeper[0], f"{deeper[1]} (via {module}.{alias.name})")

    if base:
        return base
    for alias in node.names:
        deeper = resolve(f"{module}.{alias.name}", roots, root) if module else None
        if deeper:
            return deeper
    return ("thirdparty", "unresolved: not on any path")


def shadow_warning(dotted: str, roots: list[str], root: str) -> str | None:
    """Warn when a local file has the same name as a standard library module.

    A file called ``json.py`` next to your code does shadow the real one for
    scripts, and that is worth saying out loud rather than guessing about.
    """
    top = dotted.split(".")[0]
    if top not in STDLIB or top in sys.builtin_module_names:
        return None
    local = find_in(roots, top)
    if not local:
        return None
    return f"{shorten(local, root)} shadows the standard library module {top!r}"


