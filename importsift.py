def read_source(path: str) -> tuple[str, str, str, bool]:
    """Return ``(text, encoding, newline, ends_with_newline)``.

    The encoding comes from Python's own rules, so a ``# -*- coding: ... -*-``
    cookie or a UTF-8 BOM survives a round trip untouched.
    """
    with open(path, "rb") as handle:
        raw = handle.read()
    try:
        encoding, _ = tokenize.detect_encoding(io.BytesIO(raw).readline)
    except SyntaxError:
        encoding = "utf-8"
    try:
        text = raw.decode(encoding)
    except UnicodeDecodeError:
        text = raw.decode("utf-8", "surrogateescape")
        encoding = "utf-8"
    newline = "\r\n" if "\r\n" in text else "\n"
    return text, encoding, newline, text.endswith("\n")


def split_lines(text: str) -> list[str]:
    """Split on newlines only, keeping form feeds and other control chars.

    ``str.splitlines`` also breaks on ``\\f``, ``\\v`` and friends.  Python
    allows a form feed inside source, and splitting there would move half a
    line.
    """
    if text.endswith("\n"):
        text = text[:-1]
    if text == "":
        return []
    lines = text.split("\n")
    return [line[:-1] if line.endswith("\r") else line for line in lines]


def is_comment(line: str) -> bool:
    return line.lstrip().startswith("#")


def is_blank(line: str) -> bool:
    return line.strip() == ""


def collect_comments(text: str) -> dict[int, list[str]]:
    """Map 1-based line number to the comment tokens that start on it.

    Only needed to find ``# isort:`` markers, so callers skip this entirely
    when the marker text does not appear in the file at all.  Tokenising is
    the slowest thing here and almost no file needs it.
    """
    out: dict[int, list[str]] = {}
    try:
        for token in tokenize.generate_tokens(io.StringIO(text).readline):
            if token.type == tokenize.COMMENT:
                out.setdefault(token.start[0], []).append(token.string)
    except (tokenize.TokenError, IndentationError):
        pass
    return out


def marker_comments(text: str) -> dict[int, list[str]]:
    """Comments, but only if the file could contain a marker at all."""
    if "isort:" not in text.lower():
        return {}
    return collect_comments(text)


def frozen_ranges(comments: dict[int, list[str]], line_count: int) -> list[tuple[int, int]]:
    """Line ranges between ``# isort: off`` and ``# isort: on`` (1-based)."""
    ranges: list[tuple[int, int]] = []
    opened: int | None = None
    for row in sorted(comments):
        for text in comments[row]:
            match = MARKER_RE.search(text)
            if not match:
                continue
            kind = match.group(1).lower()
            if kind == "off" and opened is None:
                opened = row
            elif kind == "on" and opened is not None:
                ranges.append((opened, row))
                opened = None
    if opened is not None:
        ranges.append((opened, line_count + 1))
    return ranges


def has_skip_marker(comments: dict[int, list[str]], first_row: int, last_row: int) -> bool:
    for row in range(first_row, last_row + 1):
        for text in comments.get(row, ()):
            match = MARKER_RE.search(text)
            if match and match.group(1).lower() == "skip":
                return True
    return False


def wants_skip_file(comments: dict[int, list[str]]) -> bool:
    for row in range(1, 6):
        for text in comments.get(row, ()):
            match = MARKER_RE.search(text)
            if match and match.group(1).lower() == "skip_file":
                return True
    return False


