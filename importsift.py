def process_text(
    text: str,
    path: str,
    root: str,
    merge: bool = False,
    newline: str = "\n",
) -> FileResult:
    """Sort one file's import blocks.  Pure: no file system writes."""
    result = FileResult(path=path, before=text)

    try:
        tree = ast.parse(text)
    except SyntaxError as exc:
        result.error = f"cannot parse: {exc.msg} (line {exc.lineno})"
        return result

    comments = marker_comments(text)
    if wants_skip_file(comments):
        result.skipped = True
        return result

    lines = split_lines(text)
    if not lines:
        result.skipped = True
        return result

    roots = search_roots(path, root)
    frozen = frozen_ranges(comments, len(lines))
    nodes = module_level_imports(tree)
    per_line = Counter(node.lineno for node in nodes)

    units: list[Unit] = []
    for node in nodes:
        unit = build_unit(node, lines, 0, roots, root, comments)
        if any(
            node.lineno <= end and (node.end_lineno or node.lineno) >= start
            for start, end in frozen
        ):
            unit.frozen = True
        # A statement that shares its line with something else cannot move:
        # the line is not its to move.  ``import a; import b`` and
        # ``x = 1; import os`` both land here.
        if per_line[node.lineno] > 1:
            unit.frozen = True
        if lines[node.lineno - 1][: node.col_offset].strip():
            unit.frozen = True
        units.extend(expand_multi_import(unit, roots, root))

    for unit in units:
        top = unit.names[0] if unit.names else unit.module_key
        warning = shadow_warning(top, roots, root)
        if warning and warning not in result.warnings:
            result.warnings.append(warning)

    if not units:
        result.skipped = True
        result.units = []
        return result

    blocks = build_blocks(units, lines)

    new_lines: list[str] = []
    cursor = 0
    for block in blocks:
        start = block[0].first
        end = block[-1].last
        if start < cursor:
            # Two statements sharing one line: the line was already emitted.
            continue
        new_lines.extend(lines[cursor:start])
        if len(block) == 1 and block[0].frozen:
            new_lines.extend(lines[start : end + 1])
        else:
            new_lines.extend(render_block(block, merge))
        cursor = end + 1
    new_lines.extend(lines[cursor:])

    new_text = newline.join(new_lines)
    if text.endswith("\n"):
        new_text += newline

    ok, reason = safe_to_write(tree, new_text)
    if not ok:
        result.error = reason
        return result

    result.after = new_text
    result.changed = new_text != text
    result.units = units
    return result


def process_file(path: str, merge: bool = False) -> FileResult:
    try:
        text, encoding, newline, ends = read_source(path)
    except OSError as exc:
        return FileResult(path=path, error=f"cannot read: {exc.strerror}")

    root = project_root(path)
    result = process_text(text, path, root, merge=merge, newline=newline)
    result.encoding = encoding
    result.newline = newline
    result.ends_with_newline = ends
    if result.changed:
        result.after_bytes = result.after.encode(encoding, "surrogateescape")
    return result


