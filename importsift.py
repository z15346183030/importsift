def collect_files(targets: list[str]) -> tuple[list[str], list[str]]:
    files: list[str] = []
    missing: list[str] = []
    for target in targets:
        if os.path.isdir(target):
            for dirpath, dirnames, filenames in os.walk(target):
                dirnames[:] = sorted(
                    d for d in dirnames if d not in SKIP_DIRS and not d.startswith(".")
                )
                for name in sorted(filenames):
                    if name.endswith(".py"):
                        files.append(os.path.join(dirpath, name))
        elif os.path.isfile(target):
            files.append(target)
        else:
            missing.append(target)
    return files, missing


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="importsift",
        description=(
            "Put every import in its place: __future__, stdlib, third-party, "
            "first-party, local.  Works out the section from the interpreter "
            "and the files on disk, and shows the evidence."
        ),
        epilog=(
            "A bare run rewrites files in place.  --check, --diff, --explain "
            "and --json only print, and never touch the file."
        ),
    )
    parser.add_argument("paths", nargs="+", metavar="PATH", help="files or directories")
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if anything would change; write nothing",
    )
    parser.add_argument("--diff", action="store_true", help="show a unified diff")
    parser.add_argument(
        "--explain",
        action="store_true",
        help="print the section of every import and the evidence for it",
    )
    parser.add_argument("--json", action="store_true", help="machine-readable report")
    parser.add_argument(
        "--merge",
        action="store_true",
        help="merge adjacent from-imports of the same module when nothing is lost",
    )
    parser.add_argument("-q", "--quiet", action="store_true", help="print nothing")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)

    files, missing = collect_files(args.paths)
    for name in missing:
        print(f"importsift: no such file or directory: {name}", file=sys.stderr)

    readonly = args.check or args.diff or args.explain or args.json
    results: list[FileResult] = []
    failures = 0

    for path in files:
        result = process_file(path, merge=args.merge)
        results.append(result)

        if result.error:
            failures += 1
            if not args.quiet and not args.json:
                print(f"error  {path}: {result.error}", file=sys.stderr)
            continue

        if args.json:
            continue

        if args.explain and result.units:
            if not args.quiet:
                print(explain(result))

        if result.changed and not result.skipped:
            if args.diff:
                print(unified_diff(result, result.newline), end="")
            elif args.check:
                if not args.quiet:
                    print(f"would sort  {path}")
            elif not readonly:
                with open(path, "wb") as handle:
                    handle.write(result.after_bytes)
                if not args.quiet:
                    print(f"sorted      {path}")

    if args.json:
        print(json.dumps([result_json(r) for r in results], indent=2, ensure_ascii=False))
        return 2 if failures else (1 if any(r.changed for r in results) and args.check else 0)

    if not args.quiet and not readonly:
        changed = sum(1 for r in results if r.changed)
        skipped = sum(1 for r in results if r.skipped)
        print(
            f"{len(files)} file(s) checked, {changed} changed, "
            f"{skipped} with no imports"
        )

    if failures:
        return 2
    if args.check and any(r.changed for r in results):
        return 1
    if missing and not files:
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
